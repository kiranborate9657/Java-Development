public class pattern1 {
    public static void main(String[] args) {
        
        System.out.println("Printing the pattern:");
        for(int i=1;i<=5;i++)
        {
            for(int j=1;j<=5+2;j++)
            {
                System.out.print(" * ");
            }
            System.out.println();
        }
    }
}
